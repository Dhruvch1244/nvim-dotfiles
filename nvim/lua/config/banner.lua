local function render(text)
  local rows = { "", "", "", "", "", "" }
  for ch in text:upper():gmatch(".") do
    local glyph = font[ch]
    if glyph then
      local w = 0
      for _, r in ipairs(glyph) do w = math.max(w, vim.fn.strdisplaywidth(r)) end
      for i, r in ipairs(glyph) do rows[i] = rows[i] .. r .. (" "):rep(w - vim.fn.strdisplaywidth(r)) end
    end
  end
  return rows
end

--- Six logo rows spelling `name`, or nil when it can't fit in `max_width` columns
--- (tries the full name, then the first word).
function M.lines(name, max_width)
  for _, candidate in ipairs({ name, name:match("^%S+") or name }) do
    local rows = render(candidate)
    local w = vim.fn.strdisplaywidth(rows[1])
    if w > 0 and w <= max_width then return rows end
  end
end

return M
